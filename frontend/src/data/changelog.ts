/**
 * 用户向更新日志 —— 页面上「版本更新日志」弹窗的唯一数据源。
 *
 * ── 怎么加一条 ──────────────────────────────────────────────────
 * 1. 在 `CHANGELOG` 最前面加一条（新版本永远在最上），字段只有三个：
 *    `version` 形如 `'v0.8.1'`，`date` 形如 `'2026-10-14'`（发版那天），
 *    `items` 是这个版本用户能感知到的变化。
 * 2. 一条一句话，用户视角写「你现在能做什么 / 什么行为变了」。
 *    不写实现，不写内部模块名，不写命令、文件名、版本号区间以外的数字。
 * 3. 硬上限：**每条 ≤ 40 个字符、必须是单行**；**一版最多 6 条**。
 *    写不下就说明这条还没想清楚，别靠砍词硬塞 —— 用户读不懂的短句等于没写。
 * 3b. **号段怎么选（v0.9.0 起执行）**：只有缺陷修复 → Z+1（`v0.8.1 → v0.8.2`）；
 *    含任何用户能感知的新能力/行为变化 → Y+1 且 Z 归零（`v0.8.2 → v0.9.0`）。
 *    判据就看本版 items 的动词：「修复…的问题/不再…」→ Z；「新增/支持/现在会/已生效」→ Y。
 *    混合版从严升 Y。X 锁死在 0，产品正式对外发布才考虑动。
 *    一次发版只动一段；没有可写的 items = 不发版。细则见
 *    `../../docs/版本更新日志-方案与口径.md` 的「三段号何时变」。
 * 4. 用词禁区与界面文案门禁是同一张表（`scripts/check-user-copy.mjs`），
 *    命中即构建红。写完先跑 `pnpm run check:copy` 再提交。
 * 5. **不写部署侧别**（「云端」「边端」这类词）。边云两份 tar 共用同一份前端产物，
 *    前端物理上拿不到自己是哪一侧；写进日志只会让用户困惑"我这是哪一侧"。
 *    一律换成用户能感知的说法：「对方画面」「打开页面」「内嵌打开时」。
 * 6. 只写用户能感知的变化。内部重构、用户看不出差别的修复，不进 items。
 * 7. **只写正向变更**〔2026-11-13 用户定〕：新增能力、修好的问题、变快变清晰。
 *    **不写**：使用限制（"要重开摄像头才生效"）、警告（"低码率会糊"）、
 *    口径收回（"分辨率只是期望值，不保证"）、功能下线、纯改名。
 *    判据是「读完这条，用户会觉得比之前好用吗」—— 说不、就不写。
 *    那些内容不是没有价值，它们的去处是发版说明（给运维）与界面上的即时提示，
 *    不是更新日志。把坏消息混进更新日志，用户会养成"这页没什么好看的"的习惯。
 * 8. **用书面语，不用口语**〔2026-11-13 用户定〕。这一条最容易失守 —— 从发版说明
 *    里摘用户向段落时，原文全是现场口语（"真的生效""莫名消失""崩了""点了有反应"
 *    "摆两个空格子"），照抄过来就像工单留言而不是更新日志。
 *    **改写方向**：`修复…的问题` / `新增…` / `…已生效` / `…可…`。
 *    **不要**：语气词（真的、原来、莫名）、口语动词（崩了、存住了、闪、卡在）、
 *    比拟（摆两个空格子、一片空白）、对话语气（点了有反应）。
 *    判据是「这条能不能直接放进产品官网的发布说明」。
 *
 * ── 来源：老版本多源汇总，新版本只从交付说明重写 ────────────────────
 * **v0.6.1 及以后**：素材是该版本交付包里的 `README.txt` 中的**用户向段落**。
 * **v0.6.0 及以前**：那几年交付说明没有"本版改了什么"段（管理不规范，见 ADR-0142），
 *   用户 2026-11-12 明确允许**从多处汇总**：交付说明与上一版的 diff、tag 区间里的
 *   feat/fix 提交、子仓前缀 tag（`conference.frontend.v0.x` / `conference.backend.v0.x`）
 *   的区间日志、ADR/evidence 里的版本锚点。
 *
 * 两条底线不变：
 * ① **绝不编造**。汇总出来的是真实发生过的改动，只是换成用户读得懂的说法；
 *    没有证据就留空，不拿"看起来合理"的话填。
 * ② **区分"我们改了什么"与"用户感知到什么"**：底层换依赖、改构建工具、改文档这类，
 *    用户没有任何感知 → 不进 items。判据是"用户会不会因此做得不一样"。
 *
 * 交付说明与其他来源都取不到可用素材的版本，**照实写 `items: []`**：弹窗显示
 * 「该版本无更新日志记录」。空着是如实记账，编一条是造假，两者不等价。
 * 还有一条容易踩：交付说明里「上一版的全部内容（本版一并带着）」是**累计段**，
 * 不是本版条目，不要摘进本版 items —— 那会让同一件事在多个版本里重复出现。
 * 同理，v0.4.0 的 tag 区间里混着**吸收进来的子仓历史**（前端 55 笔 / 后端 20 笔），
 * 那是更早的工作，不是 v0.4.0 的新东西 —— 只取 `--first-parent` 的主线提交。
 *
 * ── 纪律：加日志与改版本号必须是同一次提交 ────────────────────────
 * 版本号的唯一来源是本文件第一条的 `version`（`vite.config.ts` 刻意不注入版本号，
 * 另立一处必然漂）。也就是说「改版本号」这个动作本身就是在改这个文件。
 * 一旦把两者拆成两次提交，中间那一刻页面上显示的是「新版本号 + 旧日志」，
 * 而发版包里装的往往就是那一刻的产物 —— 版本号和日志各说各话，且没人会发现。
 * 一次提交，一条不落。
 *
 * ── 为什么没有 v0.3.0 ──────────────────────────────────────────
 * v0.3.0 与 v0.4.0 是同一份交付（交付目录被整体改名，构建时间相同），
 * 拆成两条等于凭空造一个版本差异，用户会以为自己漏装了某一版。故跳过。
 */

export type Release = {
  /** 形如 'v0.8.1' */
  version: string
  /** 形如 '2026-10-14' */
  date: string
  /** 用户向条目；空数组 = 该版本无更新日志记录 */
  items: string[]
}

